import assert from "node:assert/strict";
import test from "node:test";

import { COPILOT_CAPTION, copilotCaption, copilotRows, sourceText } from "../copilot.mjs";

const LABEL = "Generated by the Review Copilot from stored records. It is not evidence and is never used to assign a state.";

const summary = {
  case_id: "CASE_1",
  generated: true,
  label: LABEL,
  generator: "templates",
  stored: false,
  summary_id: null,
  sentences: [
    {
      text: "Release R3 changed this case from unresolved (release R2) to discordant phenotype r no mapped genotype.",
      template_text: "Release R3 changed this case from unresolved (release R2) to discordant phenotype r no mapped genotype.",
      sources: [{ kind: "case_state", id: "40" }, { kind: "case_state", id: "41" }],
    },
    {
      text: "It now depends on rule-1.",
      template_text: "It now depends on interpretation rule rule-1.",
      sources: [{ kind: "dependency", id: "rule-1", release_id: "R3", node_type: "interpretation_rule" }],
    },
  ],
};


test("every sentence shows the stored records it came from", () => {
  const rows = copilotRows(summary);
  assert.equal(rows.length, 2);
  assert.deepEqual(rows[0].sources, ["state 40", "state 41"]);
  assert.deepEqual(rows[1].sources, ["dependency record rule-1 (R3)"]);
  assert.equal(rows[1].text, "It now depends on rule-1.");
  assert.equal(sourceText({ kind: "change_event", id: "CHG-1" }), "change CHG-1");
});


test("the caption says only that the text is generated and is not evidence", () => {
  assert.equal(copilotCaption(summary), COPILOT_CAPTION);
  assert.equal(copilotCaption({ ...summary, generator: "hosted:openai/gpt-oss-20b", stored: true, summary_id: 7 }),
    COPILOT_CAPTION);
  assert.doesNotMatch(COPILOT_CAPTION, /template|model|summary \d/i);
  assert.equal(copilotCaption(null), "No summary is available for this case.");
});
